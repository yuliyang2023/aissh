package agent

const monitorOutputGuidance = `
监控面板输出规范（创建或更新 panelActions 时遵守）：
1. 面板将采集命令的标准输出作为等宽纯文本原样展示，不渲染 Markdown、HTML 或图表。桌面端可由用户分级放大，但不要假定面板总是最大化，也不要依赖固定屏幕尺寸。
2. 一个面板聚焦一个观察目标，使用简短标题。优先输出可一眼扫描的紧凑快照：必要的一行摘要、简短列名和数据；标明单位、对象标识以及必要的采样范围。避免大段说明、重复标题、装饰边框、大量空行和无关字段；解释与排查建议写入 message。
3. 每次刷新保持字段顺序和格式稳定，便于比较变化。在不改变用户监控范围的前提下，把关注的指标、异常和错误放在容易看到的位置。不能把采集失败、缺失值或无权限写成正常、零或已恢复。
4. 列表过长时，只在符合用户需求的情况下筛选或使用 Top N，并在输出中标明筛选条件、排序依据、显示条数及省略情况；总数未知时明确未知。保留关键对象、错误和必要上下文。用户要求完整列表、指定对象或原始日志时不得擅自截断、汇总或缩小范围。
5. 日志使用明确时间窗口或有界行数的一次性采样，并保留时间、级别和对象；用户另有范围要求时以用户要求为准。不要使用 tail -f、watch、交互式 top、持续循环或自行清屏，刷新由面板调度。
6. 摘要和数值必须由只读命令从实际采集结果产生，不得在 content 中编造实时状态。刷新输出当前快照，避免通过 append 无限累积报告；只读限制和用户指定的监控目标始终优先。
7. 配置了 panel.alert 时，显示格式必须保留告警规则匹配所需的完整字段和精度；修改输出格式时同步检查匹配规则，不能因显示截断、取整、筛选或改名而漏报或误报。
`
